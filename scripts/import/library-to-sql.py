"""Visual library workbooks → library_items (P5-T21).

    python -I -X utf8 scripts/import/library-to-sql.py \
        --backgrounds content/plans/Stacko_Background_Library.xlsx \
        --studio content/plans/Stacko_Content_Studio.xlsx \
        --out supabase/seed/library-items.sql

BG-xx / GFX-xx come from the Background Library sheet (newer statuses), PI-xx from the Content
Studio "Post Images" sheet. The SQL is idempotent: an entry that already exists is left alone (the
CRM is the source of truth once imported). Codes that have files in brand_assets but no row in the
sheets (e.g. BG-53) get an entry too, as `generated`. An entry whose file is already stored is at
least `generated`.
"""

import argparse
import json

import openpyxl

STATUS = {
    "to generate": "to_generate",
    "generated": "generated",
    "approved": "approved",
    "ready": "ready",
    "retired": "retired",
}


def rows(path, sheet):
    ws = openpyxl.load_workbook(path, read_only=True, data_only=True)[sheet]
    it = ws.iter_rows(values_only=True)
    head = [str(h).strip() if h else None for h in next(it)]
    return [dict(zip(head, r)) for r in it if r and r[0]]


def text(v):
    if v is None:
        return None
    s = str(v).strip()
    return None if s in ("", "—", "-") else s


def entry(code, kind, status, **f):
    return {"code": code, "kind": kind, "status": STATUS.get((status or "").strip().lower(), "to_generate"),
            **{k: text(v) for k, v in f.items()}}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--backgrounds", required=True)
    ap.add_argument("--studio", required=True)
    ap.add_argument("--out", required=True)
    ap.add_argument("--brand", default="Stacko")
    a = ap.parse_args()

    items = []
    for r in rows(a.backgrounds, "Background Library"):
        code = str(r["ID"]).strip()
        kind = "graphic" if code.startswith("GFX-") else "background"
        items.append(entry(
            code, kind, r.get("Status"),
            title=r.get("Shot") or code, collection=r.get("Set"), aspect=r.get("Aspect ratio"),
            reference=r.get("Generate from (reference image)"),
            prompt=r.get("Prompt (copy-paste, complete)"),
            negative_prompt=r.get("Negative prompt (if the tool has a field)"),
            placeholders=r.get("Green placeholders → real screen to place"),
            use_for=r.get("Use for"), when_to_use=r.get("When to use (agent guide)"),
            fits_posts=r.get("Fits these posts"), notes=r.get("Notes"),
        ))
    for r in rows(a.studio, "Post Images"):
        items.append(entry(
            str(r["ID"]).strip(), "post_image", r.get("Status"),
            title=r.get("Image") or r["ID"], collection=r.get("Theme / feature"), pillar=r.get("Pillar"),
            aspect=r.get("Aspect ratio(s)"), story=r.get("The story it tells"),
            prompt=r.get("Prompt (copy-paste, complete)"), negative_prompt=r.get("Negative prompt"),
            placeholders=r.get("Green screen → real screen"), use_for=r.get("Where to use it"),
            when_to_use=r.get("When to use it"), fits_posts=r.get("Fits these posts"),
            text_space=r.get("Space for text"), on_image_text=r.get("On-image text idea"),
        ))
    # "No prompt needed" graphics keep the sentence (it says how the file was made).
    payload = json.dumps(items, ensure_ascii=False).replace("$lib$", "")
    sql = f"""-- Visual library import (generated by scripts/import/library-to-sql.py): {len(items)} entries.
-- Idempotent: existing entries are not changed; stored files without an entry get one.
do $$
declare
  v_brand uuid := (select id from public.brands where name = {sql_str(a.brand)} order by created_at limit 1);
begin
  if v_brand is null then raise exception 'brand {a.brand} not found'; end if;

  insert into public.library_items (brand_id, code, kind, status, title, collection, pillar, aspect, reference,
    prompt, negative_prompt, placeholders, use_for, when_to_use, fits_posts, story, text_space, on_image_text, notes)
  select v_brand, i.code, i.kind, i.status, left(i.title, 300), i.collection, i.pillar, i.aspect, i.reference,
    i.prompt, i.negative_prompt, i.placeholders, i.use_for, i.when_to_use, i.fits_posts, i.story, i.text_space,
    i.on_image_text, i.notes
  from jsonb_to_recordset($lib${payload}$lib$::jsonb) as i(code text, kind text, status text, title text, collection text,
    pillar text, aspect text, reference text, prompt text, negative_prompt text, placeholders text, use_for text,
    when_to_use text, fits_posts text, story text, text_space text, on_image_text text, notes text)
  on conflict (brand_id, code) do nothing;

  -- Files already stored for a code with no entry (added to the kit after the sheets).
  insert into public.library_items (brand_id, code, kind, status, title, collection, aspect, placeholders, use_for, when_to_use)
  select distinct on (a.metadata ->> 'code') v_brand, a.metadata ->> 'code', a.asset_type::text, 'generated',
    coalesce(a.metadata ->> 'shot', a.metadata ->> 'image', a.metadata ->> 'code'), a.metadata ->> 'set',
    a.metadata ->> 'aspect', a.metadata ->> 'screens', a.metadata ->> 'use_for', a.metadata ->> 'when'
  from public.brand_assets a
  where a.brand_id = v_brand and a.asset_type::text in ('background', 'graphic', 'post_image')
    and a.metadata ->> 'code' ~ '^(BG|GFX|PI|SC|OB|SE)-[0-9]{{2,3}}$'
  order by a.metadata ->> 'code', a.version desc
  on conflict (brand_id, code) do nothing;

  -- A stored file means the image exists.
  update public.library_items i set status = 'generated'
  where i.brand_id = v_brand and i.status = 'to_generate'
    and exists (select 1 from public.brand_assets a where a.brand_id = v_brand and a.metadata ->> 'code' = i.code);
end $$;
"""
    open(a.out, "w", encoding="utf-8").write(sql)
    print(f"{len(items)} entries → {a.out}")


def sql_str(s):
    return "'" + s.replace("'", "''") + "'"


if __name__ == "__main__":
    main()
