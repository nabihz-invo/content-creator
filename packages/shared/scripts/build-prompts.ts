/**
 * Embeds prompts/*.md into src/prompts/templates.generated.ts so every runtime
 * (Edge Functions, workers, CRM) gets the same text without file access.
 * Run: pnpm --filter @cc/shared prompts:build
 */
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
export const PROMPTS_DIR = join(here, "../prompts");
export const GENERATED = join(here, "../src/prompts/templates.generated.ts");

export function generate(): string {
  const files = readdirSync(PROMPTS_DIR)
    .filter((f) => /^[a-z-]+\.v\d+\.md$/.test(f))
    .sort();
  const entries = files.map(
    (f) =>
      `  ${JSON.stringify(f.replace(/\.md$/, ""))}: ${JSON.stringify(readFileSync(join(PROMPTS_DIR, f), "utf8"))},`,
  );
  return `// GENERATED by scripts/build-prompts.ts from prompts/*.md — do not edit.\nexport const TEMPLATES: Record<string, string> = {\n${entries.join("\n")}\n};\n`;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  writeFileSync(GENERATED, generate());
  console.log(`wrote ${GENERATED}`);
}
